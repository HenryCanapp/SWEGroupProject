create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (user_id, username)
  values (new.id, lower(trim(new.raw_user_meta_data ->> 'username')));
  return new;
end;
$$;

drop trigger if exists create_profile_after_signup on auth.users;
create trigger create_profile_after_signup
  after insert on auth.users
  for each row execute procedure public.create_profile_for_new_user();

create table if not exists public.friend_requests (
  id uuid primary key default gen_random_uuid(),
  requester_id uuid not null references auth.users (id) on delete cascade,
  addressee_id uuid not null references auth.users (id) on delete cascade,
  user_low uuid not null references auth.users (id) on delete cascade,
  user_high uuid not null references auth.users (id) on delete cascade,
  status text not null default 'pending'
    check (status in ('pending', 'accepted', 'declined', 'removed')),
  created_at timestamptz not null default now(),
  responded_at timestamptz,
  check (requester_id <> addressee_id),
  check (user_low < user_high),
  check (
    (requester_id = user_low and addressee_id = user_high)
    or (requester_id = user_high and addressee_id = user_low)
  )
);

create unique index if not exists friend_requests_active_pair_idx
  on public.friend_requests (user_low, user_high)
  where status in ('pending', 'accepted');
create index if not exists friend_requests_addressee_created_idx
  on public.friend_requests (addressee_id, created_at desc);

create table if not exists public.social_notifications (
  id bigint generated by default as identity primary key,
  recipient_id uuid not null references auth.users (id) on delete cascade,
  actor_id uuid not null references auth.users (id) on delete cascade,
  request_id uuid not null references public.friend_requests (id) on delete cascade,
  notification_type text not null
    check (notification_type in ('friend_request', 'friend_request_accepted', 'friend_request_declined')),
  created_at timestamptz not null default now()
);

create index if not exists social_notifications_recipient_created_idx
  on public.social_notifications (recipient_id, created_at desc, id desc);

alter table public.friend_requests enable row level security;
alter table public.social_notifications enable row level security;
revoke all on public.friend_requests, public.social_notifications from public, anon, authenticated;

drop function if exists public.search_profiles(text);
create function public.search_profiles(search_term text)
returns table (
  user_id uuid,
  username text,
  display_name text,
  avatar_uri text,
  relationship_status text
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    profile.user_id,
    profile.username,
    profile.display_name,
    profile.avatar_uri,
    case
      when relationship.status = 'accepted' then 'friends'
      when relationship.status = 'pending' and relationship.requester_id = (select auth.uid())
        then 'pending_sent'
      when relationship.status = 'pending' then 'pending_received'
      else 'none'
    end
  from public.profiles as profile
  left join lateral (
    select request.status, request.requester_id
    from public.friend_requests as request
    where request.user_low = least((select auth.uid()), profile.user_id)
      and request.user_high = greatest((select auth.uid()), profile.user_id)
      and request.status in ('pending', 'accepted')
    order by request.created_at desc
    limit 1
  ) as relationship on true
  where auth.uid() is not null
    and profile.user_id <> (select auth.uid())
    and length(trim(search_term)) >= 2
    and position(lower(trim(search_term)) in lower(profile.username)) > 0
  order by profile.username
  limit 20;
$$;

revoke all on function public.search_profiles(text) from public, anon;
grant execute on function public.search_profiles(text) to authenticated;

create or replace function public.send_friend_request(target_user_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  request_id uuid;
  existing_status text;
  existing_requester_id uuid;
begin
  if current_user_id is null then
    raise exception 'Authentication is required.';
  end if;
  if target_user_id = current_user_id then
    raise exception 'You cannot send a friend request to yourself.';
  end if;
  if not exists (select 1 from public.profiles where user_id = target_user_id) then
    raise exception 'That user could not be found.';
  end if;

  select request.status, request.requester_id
  into existing_status, existing_requester_id
  from public.friend_requests as request
  where request.user_low = least(current_user_id, target_user_id)
    and request.user_high = greatest(current_user_id, target_user_id)
    and request.status in ('pending', 'accepted')
  order by request.created_at desc
  limit 1;

  if existing_status = 'accepted' then
    raise exception 'You are already friends.';
  elsif existing_status = 'pending' and existing_requester_id = current_user_id then
    raise exception 'Your friend request is already pending.';
  elsif existing_status = 'pending' then
    raise exception 'This user has already sent you a friend request.';
  end if;

  insert into public.friend_requests (requester_id, addressee_id, user_low, user_high)
  values (
    current_user_id,
    target_user_id,
    least(current_user_id, target_user_id),
    greatest(current_user_id, target_user_id)
  )
  returning id into request_id;

  insert into public.social_notifications (recipient_id, actor_id, request_id, notification_type)
  values (target_user_id, current_user_id, request_id, 'friend_request');
end;
$$;

create or replace function public.respond_to_friend_request(request_id uuid, accept_request boolean)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  original_requester_id uuid;
begin
  if current_user_id is null then
    raise exception 'Authentication is required.';
  end if;

  update public.friend_requests
  set status = case when accept_request then 'accepted' else 'declined' end,
      responded_at = now()
  where id = request_id
    and addressee_id = current_user_id
    and status = 'pending'
  returning requester_id into original_requester_id;

  if not found then
    raise exception 'This friend request is no longer available.';
  end if;

  insert into public.social_notifications (recipient_id, actor_id, request_id, notification_type)
  values (
    original_requester_id,
    current_user_id,
    request_id,
    case when accept_request then 'friend_request_accepted' else 'friend_request_declined' end
  );
end;
$$;

create or replace function public.remove_friend(friend_user_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
begin
  if current_user_id is null then
    raise exception 'Authentication is required.';
  end if;

  update public.friend_requests
  set status = 'removed', responded_at = now()
  where user_low = least(current_user_id, friend_user_id)
    and user_high = greatest(current_user_id, friend_user_id)
    and status = 'accepted';

  if not found then
    raise exception 'This user is not currently your friend.';
  end if;
end;
$$;

create or replace function public.get_friends()
returns table (
  user_id uuid,
  username text,
  display_name text,
  avatar_uri text
)
language sql
stable
security definer
set search_path = ''
as $$
  select profile.user_id, profile.username, profile.display_name, profile.avatar_uri
  from public.friend_requests as request
  join public.profiles as profile
    on profile.user_id = case
      when request.requester_id = (select auth.uid()) then request.addressee_id
      else request.requester_id
    end
  where (request.requester_id = (select auth.uid()) or request.addressee_id = (select auth.uid()))
    and request.status = 'accepted'
  order by profile.username;
$$;

create or replace function public.get_friend_notifications()
returns table (
  notification_id bigint,
  notification_type text,
  request_id uuid,
  request_status text,
  actor_id uuid,
  actor_username text,
  actor_display_name text,
  actor_avatar_uri text,
  created_at timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    notification.id,
    notification.notification_type,
    notification.request_id,
    request.status,
    notification.actor_id,
    profile.username,
    profile.display_name,
    profile.avatar_uri,
    notification.created_at
  from public.social_notifications as notification
  join public.friend_requests as request on request.id = notification.request_id
  join public.profiles as profile on profile.user_id = notification.actor_id
  where notification.recipient_id = (select auth.uid())
  order by notification.created_at desc, notification.id desc
  limit 15;
$$;

