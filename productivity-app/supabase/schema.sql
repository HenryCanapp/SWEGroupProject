create table if not exists public.profiles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  username text not null unique,
  display_name text not null default '',
  about_me text not null default '',
  avatar_uri text not null default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  title text not null,
  completed smallint not null default 0 check (completed in (0, 1)),
  created_at timestamptz not null default now()
);

create table if not exists public.events_habits (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  title text not null,
  type text not null check (type in ('event', 'habit')),
  date text not null default '',
  time text not null default '',
  location text not null default '',
  details text not null default '',
  importance integer not null default 3,
  recurrence text not null default 'weekly',
  selected_days text not null default '[]',
  day_times text not null default '{}',
  created_at timestamptz not null default now()
);

create index if not exists tasks_user_created_idx on public.tasks (user_id, created_at desc);
create index if not exists events_habits_user_created_idx
  on public.events_habits (user_id, created_at desc, id desc);

alter table public.profiles enable row level security;
alter table public.tasks enable row level security;
alter table public.events_habits enable row level security;

grant select, insert, update on public.profiles to authenticated;
grant select, insert on public.tasks to authenticated;
grant select, insert, update on public.events_habits to authenticated;
grant usage, select on sequence public.tasks_id_seq, public.events_habits_id_seq to authenticated;

drop policy if exists "Users can read their profile" on public.profiles;
create policy "Users can read their profile" on public.profiles
  for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Users can create their profile" on public.profiles;
create policy "Users can create their profile" on public.profiles
  for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Users can update their profile" on public.profiles;
create policy "Users can update their profile" on public.profiles
  for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

